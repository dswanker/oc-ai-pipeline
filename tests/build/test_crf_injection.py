class TestApplyCrfStandards:
    def test_injects_missing_field(self, apply_crf, minimal_spec):
        spec = copy.deepcopy(minimal_spec)
        files = [('QUESTIONS.csv', QUESTIONS_CSV), ('CHOICES.csv', CHOICES_CSV)]
        result = apply_crf(spec, files, [])
        ae = next(f for f in result['forms'] if f['form_id'] == 'AE')
        names = [r['name'] for r in ae['survey']]
        assert 'AESEV' in names, f"AESEV not injected — got: {names}"

    def test_does_not_inject_duplicates(self, apply_crf, minimal_spec):
        spec = copy.deepcopy(minimal_spec)
        files = [('QUESTIONS.csv', QUESTIONS_CSV), ('CHOICES.csv', CHOICES_CSV)]
        result = apply_crf(spec, files, [])
        ae = next(f for f in result['forms'] if f['form_id'] == 'AE')
        names = [r['name'] for r in ae['survey']]
        assert names.count('AETERM') == 1, "AETERM injected twice"

    def test_no_i_prefix_on_injected_fields(self, apply_crf, minimal_spec):
        spec = copy.deepcopy(minimal_spec)
        files = [('QUESTIONS.csv', QUESTIONS_CSV), ('CHOICES.csv', CHOICES_CSV)]
        result = apply_crf(spec, files, [])
        for form in result['forms']:
            for row in form['survey']:
                assert not row.get('name', '').startswith('I_'), \
                    f"I_ prefix on {row['name']!r} in {form['form_id']}"

    def test_all_injected_names_are_valid_xlsform(self, apply_crf, minimal_spec):
        spec = copy.deepcopy(minimal_spec)
        files = [('QUESTIONS.csv', QUESTIONS_CSV), ('CHOICES.csv', CHOICES_CSV)]
        result = apply_crf(spec, files, [])
        for form in result['forms']:
            for row in form['survey']:
                name = row.get('name', '')
                if name:
                    assert re.match(r'^[A-Za-z_][A-Za-z0-9_-]*$', name), \
                        f"Invalid XLSForm name {name!r} in {form['form_id']}"

    def test_ui_artifacts_not_injected(self, apply_crf, minimal_spec):
        spec = copy.deepcopy(minimal_spec)
        files = [('QUESTIONS.csv', QUESTIONS_CSV), ('CHOICES.csv', CHOICES_CSV)]
        result = apply_crf(spec, files, [])
        for form in result['forms']:
            for row in form['survey']:
                name = row.get('name', '').upper()
                assert not ('HIDE' in name and 'CLEAR' in name), \
                    f"UI artifact HIDE+CLEAR found: {name!r}"
                assert 'GENERATED' not in name, \
                    f"UI artifact GENERATED found: {name!r}"

    def test_checkbox_becomes_select_one_yn(self, apply_crf, minimal_spec):
        spec = copy.deepcopy(minimal_spec)
        files = [('QUESTIONS.csv', QUESTIONS_CSV), ('CHOICES.csv', CHOICES_CSV)]
        result = apply_crf(spec, files, [])
        ae = next(f for f in result['forms'] if f['form_id'] == 'AE')
        sae_row = next((r for r in ae['survey'] if r['name'] == 'SAE'), None)
        assert sae_row is not None, "SAE not found"
        assert sae_row.get('type') == 'select_one yn', \
            f"Checkbox SAE should be select_one yn, got {sae_row.get('type')!r}"

    def test_unmatched_form_not_modified(self, apply_crf, minimal_spec):
        spec = copy.deepcopy(minimal_spec)
        spec['forms'].append({
            "form_id": "VS", "form_title": "Vital Signs",
            "repeating": True, "survey": [
                {"type": "integer", "name": "SYSBP", "label": "Systolic BP",
                 "bind__oc_itemgroup": "VS"}
            ], "choices": []
        })
        files = [('QUESTIONS.csv', QUESTIONS_CSV), ('CHOICES.csv', CHOICES_CSV)]
        result = apply_crf(spec, files, [])
        vs = next(f for f in result['forms'] if f['form_id'] == 'VS')
        assert len(vs['survey']) == 1, "VS should not gain fields (not in QUESTIONS.csv)"

    def test_empty_files_is_noop(self, apply_crf, minimal_spec):
        spec = copy.deepcopy(minimal_spec)
        original_len = len(spec['forms'][0]['survey'])
        result = apply_crf(spec, [], [])
        assert len(result['forms'][0]['survey']) == original_len
