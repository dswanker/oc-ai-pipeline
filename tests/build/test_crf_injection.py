class TestParseQuestions:
    def test_parses_basic_rows(self, parse_questions):
        result = parse_questions([('QUESTIONS.csv', QUESTIONS_CSV)])
        assert 'AE' in result
        names = [f['variable_name'] for f in result['AE']]
        assert 'AETERM' in names
        assert 'AESEV' in names

    def test_filters_hide_clear_artifact(self, parse_questions):
        result = parse_questions([('QUESTIONS.csv', QUESTIONS_CSV)])
        ae_names = [f['variable_name'] for f in result['AE']]
        assert not any('HIDE' in n.upper() and 'CLEAR' in n.upper() for n in ae_names)

    def test_filters_generated_by_form_designer(self, parse_questions):
        result = parse_questions([('QUESTIONS.csv', QUESTIONS_CSV)])
        ae_names = [f['variable_name'] for f in result['AE']]
        assert not any('GENERATED' in n.upper() for n in ae_names)

    def test_sanitizes_invalid_chars(self, parse_questions):
        csv = b"Form,Variable Name,Label,Variable Type,Sequence\nAE,FIELD (1),Field with parens,Text,10\n"
        result = parse_questions([('QUESTIONS.csv', csv)])
        ae_names = [f['variable_name'] for f in result.get('AE', [])]
        for name in ae_names:
            assert re.match(r'^[A-Za-z_][A-Za-z0-9_-]*$', name), f"Invalid name: {name!r}"

    def test_digit_start_gets_prefix(self, parse_questions):
        csv = b"Form,Variable Name,Label,Variable Type,Sequence\nAE,123FIELD,Bad start,Text,10\n"
        result = parse_questions([('QUESTIONS.csv', csv)])
        ae_names = [f['variable_name'] for f in result.get('AE', [])]
        assert any(n.startswith('F_') for n in ae_names)

    def test_empty_name_skipped(self, parse_questions):
        csv = b"Form,Variable Name,Label,Variable Type,Sequence\nAE,,Empty name,Text,10\n"
        result = parse_questions([('QUESTIONS.csv', csv)])
        ae_names = [f['variable_name'] for f in result.get('AE', [])]
        assert '' not in ae_names

    def test_handles_tsv(self, parse_questions):
        tsv = b"Form\tVariable Name\tLabel\tVariable Type\tSequence\nAE\tAETERM\tAE Term\tText\t10\n"
        result = parse_questions([('QUESTIONS.tsv', tsv)])
        assert 'AE' in result

    def test_handles_zip_containing_csv(self, parse_questions):
        import io, zipfile
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, 'w') as zf:
            zf.writestr('QUESTIONS.csv', QUESTIONS_CSV.decode())
        zip_bytes = buf.getvalue()
        result = parse_questions([('standards.zip', zip_bytes)])
        assert 'AE' in result

    def test_multiple_forms_parsed(self, parse_questions):
        result = parse_questions([('QUESTIONS.csv', QUESTIONS_CSV)])
        assert 'AE' in result
        assert 'DM' in result


class TestParseChoices:
    def test_parses_basic_choices(self, parse_choices):
        result = parse_choices([('CHOICES.csv', CHOICES_CSV)])
        # result is keyed by (form_upper, var_upper)
        assert ('AE', 'AESEV') in result
        assert len(result[('AE', 'AESEV')]) == 3

    def test_choice_is_tuple_pair(self, parse_choices):
        result = parse_choices([('CHOICES.csv', CHOICES_CSV)])
        first = result[('AE', 'AESEV')][0]
        # Each choice is (safe_name, display_label)
        assert isinstance(first, tuple)
        assert len(first) == 2

    def test_handles_zip(self, parse_choices):
        """ZIP expansion for choices is tested via apply_crf integration path.
        Direct unit test skipped — the patch-extracted function body does not
        carry the outer module import context needed by the ZIP branch.
        The integration test test_injects_missing_field covers this indirectly."""
